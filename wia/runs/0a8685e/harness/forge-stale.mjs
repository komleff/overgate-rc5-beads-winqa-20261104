import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {ManagedGit} from './actor-b/scripts/lib/bd-managed-git.mjs';
import {prepareQueue,payloadHash,appendOutcome,planReplay} from './actor-b/scripts/lib/bd-managed-contract.mjs';
const base=path.dirname(new URL(import.meta.url).pathname.replace(/^\/(?:([A-Za-z]:))/, '$1'));
const output=path.resolve(process.argv[2]);
const actor=process.argv[3];
const repo=new ManagedGit({cwd:process.cwd()});
const state=repo.readPublished();
const rows=state.snapshot.trimEnd().split('\n').map(JSON.parse);
const row=rows.find(x=>x.id==='wqa-z5e');
if(!row)throw new Error('immutable seed record absent');
const [intent]=prepareQueue(JSON.stringify({intent_id:'forged-stale-title-001',op:'update',ref:row.id,title:'Forged'}),rows,state.ledger,{base:state.R,actor});
intent.expected[row.id].fields.title.value='Old';
intent.payload_hash=payloadHash(intent);
const replay=planReplay([intent],rows,state.ledger);
if(replay.conflicts.length!==1)throw new Error('negative must have exactly one stale precondition conflict');
const ledger=appendOutcome(state.ledger,intent,{ref:row.id});
const snapshot=rows.map(x=>JSON.stringify(x.id===row.id?{...x,title:'Forged'}:x)).join('\n')+'\n';
const candidate=repo.commitCandidate({base:state.R,snapshot,ledger});
execFileSync('git',['update-ref','refs/heads/qa/forged-stale',candidate],{cwd:process.cwd()});
const result={base:state.R,candidate,id:row.id,actor,conflicts:replay.conflicts,intent};
fs.writeFileSync(output,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
